# backend/orchestrator.py

# This file handles the conversation loop and tool execution binding for the chatbot.

import json
import logging
import re
from typing import List, Any, cast
import openai
from openai.types.chat import ChatCompletionMessageParam
from backend.config import settings
from backend.kgtools.tool_schemas import KG_TOOLS
from backend.kgtools.tools import (
    find_entity, get_relationships, find_dependencies, find_dependents, hybrid_search
)
from backend.kgtools.client import KGClient, RAGClient

logger = logging.getLogger(__name__)

client = openai.Client(
    base_url=settings.llm_base_url,
    api_key=settings.llm_api_key,
)

SYSTEM_PROMPT = (
    "You are CodeGraph Engineering Copilot. You MUST use the provided tools to inspect the codebase.\n"
    "- Structural queries (e.g., dependencies, callers): Call `find_entity` first, then `find_dependencies` or `find_dependents`.\n"
    "- Semantic queries (e.g., how, why, explain): Use `hybrid_search`.\n"
    "- Hybrid queries: Use both.\n\n"
    "STRICT FORMATTING RULES:\n"
    "1. If a tool returns an empty result (e.g., 'not found' or []), DO NOT retry the tool. You MUST immediately stop and reply EXACTLY with:\n"
    "   'I could not establish this from the indexed code and documentation.'\n"
    "2. Otherwise, ground all answers strictly in the tool results and output using this exact Markdown format:\n\n"
    "### Answer\n"
    "[Concise engineering answer here]\n\n"
    "### Flow\n"
    "[Optional ordered steps]\n\n"
    "### Evidence\n"
    "- Knowledge Graph: [List KG facts]\n"
    "- Source: [List source files]\n\n"
    "### Confidence\n"
    "[High/Medium/Low]\n\n"
    "Do not expose internal reasoning."
)

def execute_tool_call(
    func_name: str, args: dict[str, Any], kg_client: KGClient, rag_client: RAGClient
) -> str:
    """Routes a tool call request to the actual Python function."""
    try:
        if func_name == "find_entity":
            result = find_entity(args.get("name", ""), kg_client)
            # Programmatic safeguard for structural queries
            if isinstance(result, dict) and result.get("status") == "not found":
                return json.dumps({
                    "status": "empty", 
                    "instruction": "Entity not found. DO NOT retry with a different name. You MUST immediately stop and output exactly: 'I could not establish this from the indexed code and documentation.'"
                })
        elif func_name == "get_relationships":
            result = get_relationships(
                args.get("entity_id", ""), 
                args.get("direction", "both"), 
                kg_client, 
                args.get("relationship_type")
            )
        elif func_name == "find_dependencies":
            result = find_dependencies(args.get("entity_id", ""), kg_client)
        elif func_name == "find_dependents":
            result = find_dependents(args.get("entity_id", ""), kg_client)
        elif func_name == "hybrid_search":
            result = hybrid_search(
                args.get("query", ""), rag_client, args.get("top_k", 5), args.get("filters")
            )
            # Programmatic safeguard for semantic queries
            if not result:
                return json.dumps({
                    "status": "empty", 
                    "instruction": "No documents found. DO NOT retry. You MUST immediately stop and output exactly: 'I could not establish this from the indexed code and documentation.'"
                })
        else:
            return json.dumps({"error": f"Unknown tool: {func_name}"})
            
        return json.dumps(result)
    except Exception as e:
        logger.error(f"Error executing {func_name}: {e}")
        return json.dumps({"error": str(e)})

def strip_cot_tags(text: str) -> str:
    """Strips internal reasoning <thought> blocks generated by the LLM."""
    return re.sub(r'<thought>.*?</thought>', '', text, flags=re.DOTALL).strip()

def run_chat_cycle(prompt: str, kg_client: KGClient, rag_client: RAGClient) -> str:
    """
    Executes a multi-turn chat cycle, handling autonomous tool selection
    and passing tool responses back to the LLM.
    """
    messages: List[ChatCompletionMessageParam] = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": prompt},
    ]
    
    max_turns = 5
    
    for _ in range(max_turns):
        response = client.chat.completions.create(
            model=settings.llm_model,
            messages=messages,
            tools=KG_TOOLS,
            tool_choice="auto",
        )
        
        response_message = response.choices[0].message
        
        # If no tools are called, the model is providing its final synthesis
        if not response_message.tool_calls:
            return strip_cot_tags(response_message.content or "")
            
        # Append the assistant's tool-call request to the conversation history
        assistant_entry: dict[str, Any] = {
            "role": "assistant",
            "content": response_message.content,
            "tool_calls": [
                {
                    "id": tc.id,
                    "type": tc.type,
                    "function": {
                        "name": tc.function.name,
                        "arguments": tc.function.arguments,
                    },
                }
                for tc in response_message.tool_calls
            ],
        }
        messages.append(cast(ChatCompletionMessageParam, assistant_entry))
        
        # Execute each requested tool in parallel/sequence and append the results
        for tool_call in response_message.tool_calls:
            try:
                args = json.loads(tool_call.function.arguments)
            except json.JSONDecodeError:
                args = {}
                
            tool_result = execute_tool_call(tool_call.function.name, args, kg_client, rag_client)
            
            messages.append({
                "role": "tool",
                "tool_call_id": tool_call.id,
                "content": tool_result,
            })
            
    return "Error: Maximum tool iterations reached without final answer."